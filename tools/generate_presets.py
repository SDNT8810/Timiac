"""Generate embedded animation frames and hardware examples from simulator G-code."""
from pathlib import Path
import re
import json

ROOT = Path(__file__).resolve().parents[1]
SIM_AXES = "ABCDEHIJKLUV"
# Simulator A..V runs clockwise from 12; physical XYZABC / XYZABC is reversed.
HW_AXES = ["X1", "C2", "B2", "A2", "Z2", "Y2", "X2", "C1", "B1", "A1", "Z1", "Y1"]
PRESETS = {"struggle": "circular-struggle", "hour": "hour-movement", "curious": "curious-creature"}


def frames(source):
    result = []
    for number, raw in enumerate(source.splitlines(), 1):
        line = raw.split(";", 1)[0].strip()
        if not line or line == "G90":
            continue
        tokens = line.split()
        values, feed, dwell = [-1.0] * 12, 0.0, 0
        if tokens[0] == "G4" and len(tokens) == 2 and re.fullmatch(r"P\d+", tokens[1]):
            dwell = int(tokens[1][1:])
            if not 0 < dwell <= 120000:
                raise ValueError(f"Invalid dwell on line {number}")
        elif tokens[0] == "G1":
            for token in tokens[1:]:
                if not re.fullmatch(r"[ABCDEHIJKLUVF]\d+(?:\.\d+)?", token):
                    raise ValueError(f"Unsupported token {token} on line {number}")
                key, value = token[0], float(token[1:])
                if key == "F":
                    if feed or value <= 0:
                        raise ValueError(f"Invalid feed on line {number}")
                    feed = value
                else:
                    index = SIM_AXES.index(key)
                    if values[index] >= 0 or not 0 <= value <= 100:
                        raise ValueError(f"Invalid axis on line {number}")
                    values[index] = value
            if not feed or all(value < 0 for value in values):
                raise ValueError(f"Missing motion/feed on line {number}")
        else:
            raise ValueError(f"Unsupported command on line {number}: {line}")
        result.append((values, feed, dwell))
    if not result:
        raise ValueError("Empty preset")
    return result


def write_changed(path, text):
    if not path.exists() or path.read_text(encoding="utf-8") != text:
        path.write_text(text, encoding="utf-8")


def generate():
    machine = json.loads((ROOT / "machine.json").read_text())
    travel, max_feed = machine["travel_mm"], machine["max_feed_mm_min"]
    scale = travel / 100
    header = ["// Generated by tools/generate_presets.py; edit Simulator/gcodes instead.", "#pragma once", "namespace timiac {",
              "struct PresetFrame { float positions[12]; float feed; unsigned dwell; };"]
    for name, filename in PRESETS.items():
        data = frames((ROOT / f"Simulator/gcodes/{filename}.gcode").read_text(encoding="utf-8-sig"))
        if name == "struggle":
            # Preserve the travelling wave without the simulator's two rests.
            data = [frame for frame in data if not frame[2]]
        header.append(f"constexpr PresetFrame {name}Frames[] = {{")
        example = [f"; Generated from Simulator/gcodes/{filename}.gcode", f"; Hardware: {travel:g} mm stroke, maximum {max_feed:g} mm/min. Home all axes first.",
                   "; Clockwise from 12: " + " ".join(HW_AXES),
                   f"; Inverted mechanism: 0 mm = fully open/home, {travel:g} mm = closed.", "G90"]
        for positions, feed, dwell in data:
            header.append("  {{" + ", ".join(f"{v:g}" for v in positions) + f"}}, {feed:g}, {dwell}" + "},")
            if dwell:
                example.append(f"G4 P{dwell}")
            else:
                words = [f"{axis} {(100 - value) * scale:.3f}" for axis, value in zip(HW_AXES, positions) if value >= 0]
                example.append("G1 " + " ".join(words) + f" F{min(max_feed, feed * scale):.3f}")
        header.append("};")
        write_changed(ROOT / f"gcodes/{filename}.gcode", "\n".join(example) + "\n")
    header.append("}")
    write_changed(ROOT / "shared/presets_generated.h", "\n".join(header) + "\n")


if __name__ == "__main__":
    generate()
